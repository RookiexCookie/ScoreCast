"""Convert Exam_Score_Prediction.csv into js/data.js (columnar, compact).

Usage:  python tools/build_data.py
Standard library only. Re-run whenever the CSV changes.
"""
import csv
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "Exam_Score_Prediction.csv")
OUT = os.path.join(ROOT, "js", "data.js")

NUMERIC = ["study_hours", "class_attendance", "sleep_hours", "age", "exam_score"]
CATEGORICAL = ["sleep_quality", "study_method", "facility_rating",
               "gender", "course", "internet_access", "exam_difficulty"]
# Logical (not alphabetical) level order. Must match js/dataset.js.
ORDER = {
    "sleep_quality": ["poor", "average", "good"],
    "study_method": ["self-study", "online videos", "group study", "mixed", "coaching"],
    "facility_rating": ["low", "medium", "high"],
    "internet_access": ["no", "yes"],
    "exam_difficulty": ["easy", "moderate", "hard"],
}


def to_num(value):
    f = float(value)
    return int(f) if f.is_integer() else f


def main():
    with open(SRC, newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    if not rows:
        raise SystemExit("CSV is empty")

    levels = {}
    for col in CATEGORICAL:
        seen = sorted({r[col].strip().lower() for r in rows})
        if col in ORDER:
            unknown = set(seen) - set(ORDER[col])
            if unknown:
                raise SystemExit(f"Unknown levels in {col}: {sorted(unknown)}")
            levels[col] = list(ORDER[col])
        else:
            levels[col] = seen

    columns = {c: [to_num(r[c]) for r in rows] for c in NUMERIC}
    for col in CATEGORICAL:
        index = {lvl: i for i, lvl in enumerate(levels[col])}
        columns[col] = [index[r[col].strip().lower()] for r in rows]

    data = {"source": os.path.basename(SRC), "rows": len(rows), "columns": columns, "levels": levels}
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("/* Generated by tools/build_data.py from Exam_Score_Prediction.csv. Do not edit. */\n")
        fh.write("window.EXAM_DATA = ")
        json.dump(data, fh, separators=(",", ":"))
        fh.write(";\n")
    print(f"Wrote {OUT}: {len(rows)} rows, {os.path.getsize(OUT) / 1024:.0f} KB")


if __name__ == "__main__":
    main()
